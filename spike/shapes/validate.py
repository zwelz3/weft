"""Step 6: validate the stand-in instance table against the derived SHACL
shapes with pySHACL, and report which injected faults a shape caught and
which clean rows a shape flagged.

A fault counts as caught by its own shape when the validation report has a
result for the faulty row on the property the fault concerns: the bearer
property for a bearer fault, and the property behind the empty or dangling
reference column for `missing_required` and `dangling_ref`. A looser count,
any result at all on the faulty row, is reported beside it, because a row
can be flagged for an unrelated reason (see false positives below).

Usage: python3 validate.py <shapes.ttl> <instances.ttl> <instances.csv> <findings.md>
"""
import csv
import sys
from collections import defaultdict

import pyshacl
from rdflib import Graph, Namespace

LIBRARY_BASE = "https://weft.ghostsystems.ai/spike1/pump-library/"
SH = Namespace("http://www.w3.org/ns/shacl#")
MARKER = "<!-- Generated by validate.py below this line. -->"
REF_COLUMNS = {
    "pump_ref": "pump",
    "controller_ref": "controller",
    "sensor_ref": "sensor",
    "enclosure_ref": "enclosure",
}


def fault_properties(row, present_ids):
    """Local names of the properties the row's fault concerns."""
    fault = row["fault"]
    if fault in ("missing_bearer", "wrong_bearer_type", "duplicate_bearer"):
        return {"Component_bearer"}
    if fault == "missing_required":
        return {f"{row['class']}_{name}" for col, name in REF_COLUMNS.items() if not row[col]}
    if fault == "dangling_ref":
        return {
            f"{row['class']}_{name}"
            for col, name in REF_COLUMNS.items()
            if row[col] and row[col] not in present_ids
        }
    raise ValueError(f"unknown fault {fault!r}")


def measure(shapes_ttl, instances_ttl, csv_path):
    data = Graph().parse(instances_ttl, format="turtle")
    shapes = Graph().parse(shapes_ttl, format="turtle")
    conforms, results_graph, results_text = pyshacl.validate(
        data, shacl_graph=shapes, advanced=True, debug=False
    )

    # focus row id -> set of property local names with a result
    flagged = defaultdict(set)
    for result in results_graph.subjects(None, SH.ValidationResult):
        focus = str(results_graph.value(result, SH.focusNode))
        path = str(results_graph.value(result, SH.resultPath))
        flagged[focus.rsplit("/", 1)[-1]].add(path.rsplit("/", 1)[-1])

    rows = list(csv.DictReader(open(csv_path, encoding="utf-8")))
    present_ids = {row["id"] for row in rows}
    fault_rows = []
    clean_rows = []
    for row in rows:
        props = flagged.get(row["id"], set())
        if row["fault"]:
            expected = fault_properties(row, present_ids)
            fault_rows.append(
                {
                    "id": row["id"],
                    "fault": row["fault"],
                    "caught_by_own_shape": bool(expected & props),
                    "any_result": bool(props),
                    "other_properties": sorted(props - expected),
                }
            )
        else:
            clean_rows.append({"id": row["id"], "flagged_properties": sorted(props)})

    flagged_clean = [r for r in clean_rows if r["flagged_properties"]]
    summary = {
        "conforms": conforms,
        "results": len(set(results_graph.subjects(None, SH.ValidationResult))),
        "faults": len(fault_rows),
        "caught_by_own_shape": sum(r["caught_by_own_shape"] for r in fault_rows),
        "caught_any_result": sum(r["any_result"] for r in fault_rows),
        "clean_rows": len(clean_rows),
        "clean_rows_flagged": len(flagged_clean),
        "clean_flag_properties": sorted({p for r in flagged_clean for p in r["flagged_properties"]}),
    }
    return {
        "summary": summary,
        "fault_rows": fault_rows,
        "clean_rows": clean_rows,
        "report_text": results_text,
    }


def main():
    shapes_ttl, instances_ttl, csv_path, findings_path = sys.argv[1:5]
    m = measure(shapes_ttl, instances_ttl, csv_path)
    s = m["summary"]

    lines = [
        f"pySHACL conforms: {s['conforms']}. Validation results: {s['results']}.",
        "",
        f"Injected faults: {s['faults']}. Caught by the shape on the faulty property: "
        f"{s['caught_by_own_shape']}. Rows with any result: {s['caught_any_result']}.",
        "",
        f"Clean rows: {s['clean_rows']}. Clean rows with at least one result (false positives): "
        f"{s['clean_rows_flagged']}, on the properties {', '.join(s['clean_flag_properties']) or 'none'}.",
        "",
        "| Row | Fault | Caught by its own shape | Other properties flagged on the row |",
        "|---|---|---|---|",
    ]
    for r in m["fault_rows"]:
        lines.append(
            f"| {r['id']} | {r['fault']} | {'yes' if r['caught_by_own_shape'] else 'no'} | "
            f"{', '.join(r['other_properties']) or 'none'} |"
        )
    lines += ["", "| Clean row | Properties flagged |", "|---|---|"]
    for r in m["clean_rows"]:
        lines.append(f"| {r['id']} | {', '.join(r['flagged_properties']) or 'none'} |")

    # The findings file keeps its hand-written part above MARKER and
    # replaces everything below it.
    try:
        existing = open(findings_path, encoding="utf-8").read()
    except FileNotFoundError:
        existing = "# Step 6 findings\n\n"
    head = existing.split(MARKER, 1)[0]
    with open(findings_path, "w", encoding="utf-8") as f:
        f.write(
            head + MARKER + "\n\n" + "\n".join(lines)
            + "\n\n## Full pySHACL report\n\n```\n" + m["report_text"] + "\n```\n"
        )

    print(
        f"conforms={s['conforms']}; caught {s['caught_by_own_shape']}/{s['faults']} by own shape; "
        f"{s['clean_rows_flagged']}/{s['clean_rows']} clean rows flagged; -> {findings_path}"
    )


if __name__ == "__main__":
    main()
